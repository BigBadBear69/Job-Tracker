package com.jobtracker.timeline.data

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/** A raw location fix recorded by the tracking service (or imported). */
@Entity(tableName = "points", indices = [Index("time")])
data class LocationPoint(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val time: Long,
    val lat: Double,
    val lon: Double,
    val accuracy: Float,
    val speed: Float? = null,
    /** Activity reported by activity recognition around this time, e.g. "WALKING". */
    val activity: String? = null,
)

enum class SegmentType { VISIT, TRIP }

/** How a trip was made. [auto] marks modes the app can detect on its own. */
enum class TravelMode(val label: String, val auto: Boolean = false) {
    WALKING("Walking", true),
    RUNNING("Running", true),
    CYCLING("Cycling", true),
    DRIVING("Driving", true),
    MOTORCYCLE("Motorcycling"),
    BUS("Bus"),
    TRAIN("Train"),
    SUBWAY("Subway"),
    TRAM("Tram"),
    FERRY("Ferry"),
    FLYING("Flying", true),
    UNKNOWN("Moving", true),
}

/**
 * A processed piece of the timeline: either a visit (stay at one place) or a trip between visits.
 * Segments the user has changed are marked [edited] and are never regenerated by processing.
 */
@Entity(tableName = "segments", indices = [Index("startTime"), Index("endTime"), Index("placeId")])
data class Segment(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val type: SegmentType,
    val startTime: Long,
    val endTime: Long,
    /** Visit: centre of the stay. Trip: start point. */
    val lat: Double,
    val lon: Double,
    /** Trip end point (equal to lat/lon for visits). */
    val endLat: Double,
    val endLon: Double,
    val placeId: Long? = null,
    val mode: TravelMode? = null,
    val distanceMeters: Double = 0.0,
    val edited: Boolean = false,
)

enum class PlaceCategory(val label: String) { HOME("Home"), WORK("Work"), SCHOOL("School"), OTHER("Place") }

/** A named place. Visits within [radius] metres are recognised automatically. */
@Entity(tableName = "places")
data class Place(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val lat: Double,
    val lon: Double,
    val radius: Double = 100.0,
    val category: PlaceCategory = PlaceCategory.OTHER,
    val address: String? = null,
)

/** Reverse-geocoding results cached by rounded coordinate (~11 m grid). */
@Entity(tableName = "geocode_cache")
data class GeocodeEntry(
    @PrimaryKey val key: String,
    val address: String?,
    val city: String?,
    val country: String?,
)
